def _which(prog):
    for d in os.environ.get("PATH", "").split(os.pathsep):
        p = os.path.join(d, prog)
        if os.path.isfile(p) and os.access(p, os.X_OK):
            return p
    return None


def _run(cmd):
    try:
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        p.communicate()
        return p.returncode
    except Exception:
        return 127


def _try_external(pdf, out):
    """按可靠性排序试外部工具。返回用上的工具名，全失败返回 None。"""
    cands = []
    if _which("pdftotext"):
        cands.append(("pdftotext",
                      ["pdftotext", "-layout", "-enc", "UTF-8", pdf, out]))
    if _which("gs"):
        cands.append(("ghostscript-txtwrite",
                      ["gs", "-q", "-dNOPAUSE", "-dBATCH", "-dSAFER",
                       "-sDEVICE=txtwrite", "-dTextFormat=3",
                       "-sOutputFile=" + out, pdf]))
    if _which("mutool"):
        cands.append(("mutool", ["mutool", "draw", "-F", "txt", "-o", out, pdf]))
    if _which("pdf2txt.py"):
        cands.append(("pdfminer", ["pdf2txt.py", "-o", out, pdf]))
    for name, cmd in cands:
        sys.stderr.write("  try %s ...\n" % name)
        rc = _run(cmd)
        if rc == 0 and os.path.isfile(out) and os.path.getsize(out) > 20000:
            return name
        if os.path.isfile(out) and os.path.getsize(out) <= 20000:
            os.remove(out)
    return None


_STR = re.compile(br"\((?:\\.|[^\\()])*\)", re.S)
_SHOW = re.compile(
    br"(\((?:\\.|[^\\()])*\))\s*(?:Tj|')"
    br"|\[((?:[^\[\]\\]|\\.)*)\]\s*TJ"
    br"|(T\*|Td|TD|BT|ET)", re.S)
_ESC = {b"n": b"\n", b"r": b"\r", b"t": b"\t", b"b": b"\b",
        b"f": b"\f", b"(": b"(", b")": b")", b"\\": b"\\"}


def _unescape(s):
    s = s[1:-1]
    out = []
    i, n = 0, len(s)
    while i < n:
        c = s[i:i + 1]
        if c == b"\\" and i + 1 < n:
            nx = s[i + 1:i + 2]
            if nx in _ESC:
                out.append(_ESC[nx])
                i += 2
                continue
            if nx.isdigit():
                j = i + 1
                while j < n and j < i + 4 and s[j:j + 1].isdigit():
                    j += 1
                try:
                    out.append(bytes(bytearray([int(s[i + 1:j], 8) & 0xFF])))
                except Exception:
                    pass
                i = j
                continue
            if nx == b"\n":
                i += 2
                continue
            out.append(nx)
            i += 2
            continue
        out.append(c)
        i += 1
    return b"".join(out)


_TJ_ITEM = re.compile(br"\((?:\\.|[^\\()])*\)|<[0-9A-Fa-f\s]*>|-?\d+(?:\.\d+)?")


def _hexstr(tok):
    h = re.sub(br"[^0-9A-Fa-f]", b"", tok)
    if len(h) % 2:
        h += b"0"
    try:
        return bytes(bytearray(int(h[i:i + 2], 16) for i in range(0, len(h), 2)))
    except Exception:
        return b""


def _content_to_text(data):
    out = []
    for m in _SHOW.finditer(data):
        if m.group(1):
            out.append(_unescape(m.group(1)))
        elif m.group(2) is not None:
            # 逐项走 TJ 数组：大的负 kerning 就是词间空格
            # （LaTeX / FrameMaker 排版常这么干，不补就会粘成一坨）
            for im in _TJ_ITEM.finditer(m.group(2)):
                tok = im.group(0)
                if tok[:1] == b"(":
                    out.append(_unescape(tok))
                elif tok[:1] == b"<":
                    out.append(_hexstr(tok))
                else:
                    try:
                        if float(tok) <= -100.0:
                            out.append(b" ")
                    except Exception:
                        pass
        else:
            if m.group(3) in (b"T*", b"Td", b"TD", b"ET"):
                out.append(b"\n")
    txt = b"".join(out)
    return re.sub(br"\n{3,}", b"\n\n", txt)


def _pure_python(pdf, out):
    """最后兜底：只靠 zlib 解 FlateDecode 内容流，硬扫 Tj/TJ。
    没有字体编码映射，subset 字体会出乱码 —— info 的可读性分数会告诉你。"""
    fh = open(pdf, "rb")
    raw = fh.read()
    fh.close()
    pages = []
    for m in re.finditer(br"stream\r?\n", raw):
        head = raw[max(0, m.start() - 800):m.start()]
        if b"/Image" in head or b"DCTDecode" in head or b"JPXDecode" in head:
            continue
        start = m.end()
        end = raw.find(b"endstream", start)
        if end < 0:
            continue
        data = raw[start:end]
        if b"FlateDecode" in head:
            try:
                data = zlib.decompress(data)
            except Exception:
                try:
                    data = zlib.decompressobj().decompress(data)
                except Exception:
                    continue
        elif b"/Filter" in head:
            continue
        if b"Tj" not in data and b"TJ" not in data:
            continue
        t = _content_to_text(data)
        if len(t.strip()) > 20:
            pages.append(t)
    fo = open(out, "wb")
    fo.write(b"\f".join(pages))
    fo.close()
    return len(pages) > 0


def cmd_build(args):
    pdf = args.get("pdf", PDF_DEFAULT)
    work = args.get("work", WORK_DEFAULT)
    if not os.path.isfile(pdf):
        die("找不到 PDF: %s  (用 --pdf 指定)" % pdf)
    if not os.path.isdir(work):
        os.makedirs(work)
    txt = os.path.join(work, "doc.txt")
    if os.path.isfile(txt) and not args.get("force"):
        print("已存在 %s（%.1f MB）。要重建加 --force" %
              (txt, os.path.getsize(txt) / 1048576.0))
        return
    print("PDF: %s  (%.1f MB)" % (pdf, os.path.getsize(pdf) / 1048576.0))
    tool = _try_external(pdf, txt)
    if tool is None:
        print("  外部工具都不可用/失败，回退纯 python 解析（可能有乱码）")
        if not _pure_python(pdf, txt):
            die("纯 python 回退也没提出文本。把 `which pdftotext gs mutool` 的结果发出来。")
        tool = "pure-python(degraded)"
    fh = open(os.path.join(work, "extractor.txt"), "w")
    fh.write(tool + "\n")
    fh.close()
    print("OK  抽取器=%s  ->  %s (%.1f MB)" %
          (tool, txt, os.path.getsize(txt) / 1048576.0))
    cmd_info(args)


