def collapse(t):
    return re.sub(r"[ \t\x0b\r]+", " ", re.sub(r"\n{2,}", "\n", t)).strip()


DEF_KW = ("default", "specifies", "valid values", "choices", "the default",
          "possible values", "one of", "syntax")


def find_hits(pages, term, max_hits):
    """返回 [(score, page_no, line_no, 上下文原文)]，按 score 降序、同页去重。"""
    hits = []
    tl = term.lower()
    for pi, ptext in enumerate(pages):
        if tl not in ptext.lower():
            continue
        lines = ptext.split("\n")
        for li, line in enumerate(lines):
            low = line.lower()
            if tl not in low:
                continue
            st = line.strip()
            score = 1
            if st.lower().startswith(tl):
                score += 10          # 词条开头 = 多半是定义
            if re.match(r"^-?[\w_]+$", st):
                score += 3           # 独占一行
            nxt = " ".join(lines[li + 1:li + 4]).lower()
            for kw in DEF_KW:
                if kw in nxt or kw in low:
                    score += 4
                    break
            if len(st) > 200:
                score -= 2           # 正文长段落，多半只是顺带提一嘴
            hits.append((score, pi + 1, li + 1, "\n".join(lines[li:li + 14])))
    hits.sort(key=lambda x: (-x[0], x[1]))
    seen, out = set(), []
    for h in hits:
        if h[1] in seen:
            continue
        seen.add(h[1])
        out.append(h)
        if len(out) >= max_hits:
            break
    return out, len(hits)


class Chunker(object):
    def __init__(self, work, prefix, limit):
        self.work, self.prefix, self.limit = work, prefix, limit
        self.n, self.buf, self.size = 0, [], 0
        self.files = []

    def add(self, text):
        b = text.encode("utf-8", "replace")
        if self.size and self.size + len(b) > self.limit:
            self.flush()
        self.buf.append(text)
        self.size += len(b)

    def flush(self):
        if not self.buf:
            return
        self.n += 1
        path = os.path.join(self.work, "%s_%02d.txt" % (self.prefix, self.n))
        fh = open(path, "wb")
        fh.write(("".join(self.buf)).encode("utf-8", "replace"))
        fh.close()
        self.files.append((path, os.path.getsize(path)))
        self.buf, self.size = [], 0

    def report(self):
        print("写出 %d 个分块（每块 <= %d 字节）：" % (len(self.files), self.limit))
        for p, sz in self.files:
            print("  %s  %d bytes" % (p, sz))


def cmd_ask(args):
    work = args.get("work", WORK_DEFAULT)
    s, pages, starts = load(work)
    only = args.get("only")
    per_hit = int(args.get("per-hit", 700))
    max_hits = int(args.get("hits", 2))
    limit = int(args.get("budget", CHUNK_BYTES))
    fields = FIELDS
    if only:
        want = set(x.strip() for x in only.split(","))
        fields = [f for f in FIELDS if f[0] in want]
        missing = want - set(f[0] for f in fields)
        if missing:
            print("[!] 不认识的 key: %s" % ", ".join(sorted(missing)))
    ch = Chunker(work, "answers", limit)
    ch.add("# extUser.pdf 字段探查  (%d 字段, 每命中<=%dB, 每字段<=%d 命中)\n"
           % (len(fields), per_hit, max_hits))
    for key, terms, question in fields:
        blk = ["\n===== %s =====\n问: %s\n" % (key, question)]
        got = False
        for term in terms:
            hits, total = find_hits(pages, term, max_hits)
            if not hits:
                blk.append("  [%s] 0 命中\n" % term)
                continue
            got = True
            blk.append("  [%s] 共 %d 命中, 取前 %d:\n" % (term, total, len(hits)))
            for score, pg, ln, ctx in hits:
                c = collapse(ctx)
                if len(c) > per_hit:
                    c = c[:per_hit] + " ...[截断]"
                blk.append("  -- p.%d (score %d) --\n  %s\n" % (pg, score, c))
        if not got:
            blk.append("  ** 全部搜索词零命中 —— 这个选项可能不在 extUser.pdf 里，"
                       "去同目录别的书（extCmdRef 之类）找 **\n")
        ch.add("".join(blk))
    ch.flush()
    ch.report()
    print("\n把这些文件依次带出来即可。")


def cmd_toc(args):
    """扫全文里所有 '-option' 词元 + 首见页，输出很小，用来确认这本书对不对。"""
    work = args.get("work", WORK_DEFAULT)
    s, pages, starts = load(work)
    seen = {}
    pat = re.compile(r"(?<![\w-])-([a-z][a-z0-9_]{3,})\b")
    for pi, ptext in enumerate(pages):
        for m in pat.finditer(ptext):
            k = m.group(1)
            if k not in seen:
                seen[k] = [pi + 1, 0]
            seen[k][1] += 1
    minc = int(args.get("min", 2))
    items = sorted(seen.items(), key=lambda kv: -kv[1][1])
    ch = Chunker(work, "toc", int(args.get("budget", CHUNK_BYTES)))
    ch.add("# 全文出现过的 -option 词元（>=%d 次），按频次排序\n" % minc)
    for k, pc in items:
        if pc[1] < minc:
            continue
        ch.add("-%-40s %5d 次  首见 p.%d\n" % (k, pc[1], pc[0]))
    ch.flush()
    ch.report()


def cmd_grep(args):
    work = args.get("work", WORK_DEFAULT)
    s, pages, starts = load(work)
    terms = args.get("_pos", [])
    if not terms:
        die("用法: grep PATTERN [PATTERN...]")
    per_hit = int(args.get("per-hit", 900))
    max_hits = int(args.get("hits", 6))
    ch = Chunker(work, "grep", int(args.get("budget", CHUNK_BYTES)))
    for term in terms:
        hits, total = find_hits(pages, term, max_hits)
        ch.add("\n===== %s ===== (%d 命中, 取 %d)\n" % (term, total, len(hits)))
        for score, pg, ln, ctx in hits:
            c = collapse(ctx)
            if len(c) > per_hit:
                c = c[:per_hit] + " ...[截断]"
            ch.add("-- p.%d --\n%s\n" % (pg, c))
    ch.flush()
    ch.report()


def cmd_page(args):
    work = args.get("work", WORK_DEFAULT)
    s, pages, starts = load(work)
    pos = args.get("_pos", [])
    if not pos:
        die("用法: page N [M]   （倒出第 N..M 页原文）")
    a = int(pos[0])
    b = int(pos[1]) if len(pos) > 1 else a
    ch = Chunker(work, "page", int(args.get("budget", CHUNK_BYTES)))
    for i in range(a, b + 1):
        if 1 <= i <= len(pages):
            ch.add("\n========== p.%d ==========\n%s\n" % (i, pages[i - 1]))
    ch.flush()
    ch.report()


