def die(msg):
    sys.stderr.write("ERROR: %s\n" % msg)
    sys.exit(1)


def _u(x):
    """py2 hands us argv as byte str; everything downstream is unicode."""
    if isinstance(x, bytes):
        return x.decode("utf-8", "replace")
    return x


def parse_argv(argv):
    argv = [_u(x) for x in argv]
    args, pos = {}, []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a.startswith("--"):
            k = a[2:]
            if "=" in k:
                k, v = k.split("=", 1)
                args[k] = v
            elif k == "force":
                args[k] = True
            else:
                i += 1
                args[k] = argv[i] if i < len(argv) else ""
        else:
            pos.append(a)
        i += 1
    args["_pos"] = pos
    return args


CMDS = {"build": cmd_build, "info": cmd_info, "ask": cmd_ask,
        "toc": cmd_toc, "grep": cmd_grep, "page": cmd_page}


if __name__ == "__main__":
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help", "help"):
        print(__doc__)
        sys.exit(0)
    sub = sys.argv[1]
    if sub not in CMDS:
        die("未知子命令 %r，可用: %s" % (sub, ", ".join(sorted(CMDS))))
    a = parse_argv(sys.argv[2:])
    a.setdefault("work", WORK_DEFAULT)
    a.setdefault("pdf", PDF_DEFAULT)
