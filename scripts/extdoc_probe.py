def load(work):
    txt = os.path.join(work, "doc.txt")
    if not os.path.isfile(txt):
        die("还没建缓存。先跑：python %s build" % os.path.basename(sys.argv[0]))
    fh = open(txt, "rb")
    data = fh.read()
    fh.close()
    s = data.decode("utf-8", "replace")
    pages = s.split("\f")
    starts, off = [], 0
    for p in pages:
        starts.append(off)
        off += len(p) + 1
    return s, pages, starts


def readability(s):
    sample = s[:400000]
    if not sample:
        return 0.0
    good = 0
    for c in sample:
        if c.isalnum() or c in " .,-_()/\n\t:;=\"'":
            good += 1
    return good / float(len(sample))


def cmd_info(args):
    work = args.get("work", WORK_DEFAULT)
    s, pages, starts = load(work)
    ex = "?"
    p = os.path.join(work, "extractor.txt")
    if os.path.isfile(p):
        fh = open(p)
        ex = fh.read().strip()
        fh.close()
    r = readability(s)
    print("抽取器      : %s" % ex)
    print("文本大小    : %.1f MB" % (len(s) / 1048576.0))
    print("页数        : %d" % len(pages))
    print("可读性      : %.3f  (>0.90 好；<0.80 说明字体编码没解开，换抽取器)" % r)
    for probe in ("Quantus", "extraction", "output_db", "-decoupling_factor",
                  "extract_type", "command file"):
        print("  含 %-24s : %d 次" % (repr(probe), s.count(probe)))
    if r < 0.80:
        print("\n[!] 可读性偏低。把 `which pdftotext gs mutool acroread` 的输出发出来。")


